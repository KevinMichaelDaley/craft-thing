#!/usr/bin/env python3
"""Generate Planck/CIE RGB lookup; no spectral integration at frame time.

Planck law: https://pbr-book.org/4ed/Radiometry,_Spectra,_and_Color/Light_Emission
Analytic CIE matching functions: Wyman, Sloan, Shirley (2013),
Simple Analytic Approximations to the CIE XYZ Color Matching Functions.
RGB values are normalized linear sRGB; radiometric scale is supplied separately.
"""
import math
from pathlib import Path


def gaussian(wavelength, center, left, right):
    t = (wavelength-center)*(left if wavelength<center else right)
    return math.exp(-.5*t*t)


def color(temperature):
    xyz = [0., 0., 0.]
    for w in range(360, 831):
        x = .362*gaussian(w,442,.0624,.0374)+1.056*gaussian(w,599.8,.0264,.0323)-.065*gaussian(w,501.1,.049,.0382)
        y = .821*gaussian(w,568.8,.0213,.0247)+.286*gaussian(w,530.9,.0613,.0322)
        z = 1.217*gaussian(w,437,.0845,.0278)+.681*gaussian(w,459,.0385,.0725)
        wavelength = w*1e-9
        spectrum = wavelength**-5/math.expm1(.01438776877/(wavelength*temperature))
        xyz = [a+spectrum*b for a,b in zip(xyz,(x,y,z))]
    x,y,z = xyz
    rgb = [max(0.,3.2406*x-1.5372*y-.4986*z),max(0.,-.9689*x+1.8758*y+.0415*z),max(0.,.0557*x-.204*y+1.057*z)]
    return [v/max(rgb) for v in rgb], y/temperature**4


samples = [color(t) for t in range(500,12001,250)]
rows = [sample[0] for sample in samples]
# Normalize the interpolated table, including its finite temperature spacing.
reference = samples[5][1]*.8+samples[6][1]*.2
efficiency = [sample[1]/reference for sample in samples]
header = '''#ifndef DC_BLACKBODY_H
#define DC_BLACKBODY_H
#define FR_FIRE_EMISSION_SURFACE 1u
#define FR_FIRE_EMISSION_AIRBORNE 2u
#define FR_FIRE_EMISSION_MAGIC 4u
/* Generated by tools/generate_blackbody.py. Linear RGB, kelvin, finite power.
 * Magical override changes chromaticity only; it does not create heat or fuel. */
#ifdef __STDC_VERSION__
#include <math.h>
static const float fr_blackbody_table[][3] = {
'''
header += ',\n'.join('    {'+', '.join(f'{v:.8f}f' for v in row)+'}' for row in rows)
header += '''
};
/** Sample thermal chromaticity or an explicit magical color at admitted power. */
static inline void fr_blackbody_rgb(float temperature,float power,int magical,const float override[3],float out[3]) {
    float coordinate=fmaxf(0.f,fminf(46.f,(temperature-500.f)/250.f));
    int lo=(int)coordinate,hi=lo<46?lo+1:46;float blend=coordinate-(float)lo;
    for(int i=0;i<3;i++) out[i]=fmaxf(0.f,power)*(magical?fmaxf(0.f,override[i]):
        fr_blackbody_table[lo][i]+blend*(fr_blackbody_table[hi][i]-fr_blackbody_table[lo][i]));
}
#else
const vec3 fr_blackbody_table[47]=vec3[47](
'''
header += ',\n'.join('    vec3('+', '.join(f'{v:.8f}' for v in row)+')' for row in rows)
header += '''
);
vec3 fr_blackbody_rgb(float temperature,float power,bool magical,vec3 override_color) {
    float coordinate=clamp((temperature-500.)/250.,0.,46.);
    int lo=int(coordinate),hi=min(lo+1,46);
    return max(0.,power)*(magical?max(vec3(0.),override_color):mix(fr_blackbody_table[lo],fr_blackbody_table[hi],fract(coordinate)));
}
#endif
#endif
'''
# Separate chromaticity from the photopic fraction of finite bolometric power.
extra = "\n#ifdef __STDC_VERSION__\nstatic const float fr_blackbody_efficiency[47]={\n"
extra += ",\n".join(f"    {v:.10e}f" for v in efficiency)
extra += "\n};\nstatic inline float fr_blackbody_visible_efficiency(float temperature) {\n    if(temperature<500.f) return 0.f;\n    float coordinate=fmaxf(0.f,fminf(46.f,(temperature-500.f)/250.f));\n    int lo=(int)coordinate,hi=lo<46?lo+1:46;\n    return fr_blackbody_efficiency[lo]+(coordinate-(float)lo)*(fr_blackbody_efficiency[hi]-fr_blackbody_efficiency[lo]);\n}\n#else\nconst float fr_blackbody_efficiency[47]=float[47](\n"
extra += ",\n".join(f"    {v:.10e}" for v in efficiency)
extra += "\n);\nfloat fr_blackbody_visible_efficiency(float temperature) {\n    if(temperature<500.) return 0.;\n    float coordinate=clamp((temperature-500.)/250.,0.,46.);\n    int lo=int(coordinate),hi=min(lo+1,46);\n    return mix(fr_blackbody_efficiency[lo],fr_blackbody_efficiency[hi],fract(coordinate));\n}\n#endif\n"
header = header.rsplit("#endif",1)[0]+extra+"#endif\n"
Path(__file__).resolve().parents[1].joinpath('include/dungeoncraft/blackbody.h').write_text(header)
